func TestPlanPropagatesContextCancellation(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	application := New(&fakeGitSource{err: context.Canceled}, &fakeWorktree{}, &fakeState{}, nil, nil)
	_, err := application.Plan(ctx, testPlanInput())
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("Plan() error = %v, want context cancellation", err)
	}
}

