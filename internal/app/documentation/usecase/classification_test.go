func TestClassifyRole(t *testing.T) {
	tests := []struct {
		path    string
		content string
		role    sharedmodel.SourceRole
	}{
		{path: "cmd/server/main.go", role: sharedmodel.RoleProductionSource},
		{path: "api/service.proto", role: sharedmodel.RoleContract},
		{path: "migrations/001.sql", role: sharedmodel.RoleDatabase},
		{path: ".github/workflows/ci.yml", role: sharedmodel.RoleRuntimeConfiguration},
		{path: "package.json", role: sharedmodel.RoleDependencyManifest},
		{path: "src/server_test.go", role: sharedmodel.RoleTest},
		{path: "src/generated/client.go", role: sharedmodel.RoleGeneratedCode},
		{path: "fixtures/response.json", role: sharedmodel.RoleFixture},
		{path: "go.sum", role: sharedmodel.RoleLockFile},
		{path: "README.md", role: sharedmodel.RoleProse},
		{path: "source.unknown", role: sharedmodel.RoleUnknownSource},
		{path: "web/styles.css", role: sharedmodel.RoleProductionSource},
		{path: "requirements-dev.txt", role: sharedmodel.RoleDependencyManifest},
		{path: "tool", content: "#!/usr/bin/env python3\n", role: sharedmodel.RoleProductionSource},
		{path: "generated.go", content: "// Code generated by tool. DO NOT EDIT.\n", role: sharedmodel.RoleGeneratedCode},
	}

	for _, test := range tests {
		t.Run(test.path, func(t *testing.T) {
			role, _ := classifyRole(test.path, []byte(test.content), nil)
			if role != test.role {
				t.Fatalf("classifyRole() = %q, want %q", role, test.role)
			}
		})
	}
}

func TestClassifyRoleUsesFirstOverride(t *testing.T) {
	overrides := []documentationmodel.RoleOverride{
		{Pattern: "features/**", Role: sharedmodel.RoleContract},
		{Pattern: "**/*.feature", Role: sharedmodel.RoleTest},
	}
	role, reason := classifyRole("features/payment.feature", nil, overrides)
	if role != sharedmodel.RoleContract || reason != "role_override" {
		t.Fatalf("classifyRole() = %q, %q, want contract override", role, reason)
	}
}

func TestPlanScansAndClassifiesWithoutReadingDeniedPaths(t *testing.T) {
	entries := []sharedmodel.TrackedEntry{
		{Path: "vendor/dependency.go", Mode: "100644"},
		{Path: "main_test.go", Mode: "100644"},
		{Path: "docs/generated/index.md", Mode: "100644"},
		{Path: "large.go", Mode: "100644"},
		{Path: "main.go", Mode: "100644"},
		{Path: ".env", Mode: "100644"},
		{Path: "README.md", Mode: "100644"},
		{Path: "image.bin", Mode: "100644"},
	}
	worktree := &fakeWorktree{contents: map[string]sharedmodel.FileContent{
		"main.go":      textContent("main.go", "package main\n"),
		"main_test.go": textContent("main_test.go", "package main\n"),
		"README.md":    textContent("README.md", "# Repository\n"),
		"image.bin":    textContent("image.bin", "\x00binary"),
		"large.go":     {Path: "large.go", Size: 1000, Data: []byte("package"), Truncated: true},
	}}
	application := New(&fakeGitSource{root: "/repository", entries: entries}, worktree, &fakeState{result: sharedmodel.StateLoadResult{Missing: true}}, nil, nil)

	result, err := application.Plan(context.Background(), testPlanInput())
	if err != nil {
		t.Fatalf("Plan() error = %v", err)
	}
	if result.TrackedPaths != 8 || result.IncludedPaths != 3 || result.TriggeringPaths != 1 || result.ExcludedPaths != 5 {
		t.Errorf("result counts = %+v, want tracked=8 included=3 triggering=1 excluded=5", result)
	}
	wantReads := []string{"README.md", "image.bin", "large.go", "main.go", "main_test.go"}
	if !reflect.DeepEqual(worktree.reads, wantReads) {
		t.Errorf("read paths = %v, want %v", worktree.reads, wantReads)
	}
	if !sortDecisions(result.Files) {
		t.Errorf("decisions are not sorted: %+v", result.Files)
	}
	decision := decisionByPath(t, result.Files, ".env")
	if decision.Role != sharedmodel.RoleSecret || decision.Reason != "secret_filename" {
		t.Errorf("secret decision = %+v", decision)
	}
}

func TestPlanRejectsHighConfidenceSecretWithoutExposingValue(t *testing.T) {
	secret := "AKIA1234567890ABCDEF"
	worktree := &fakeWorktree{contents: map[string]sharedmodel.FileContent{
		"main.go": textContent("main.go", "package main\nconst token = \""+secret+"\"\n"),
	}}
	application := New(&fakeGitSource{root: "/repository", entries: []sharedmodel.TrackedEntry{{Path: "main.go", Mode: "100644"}}}, worktree, &fakeState{result: sharedmodel.StateLoadResult{Missing: true}}, nil, nil)

	_, err := application.Plan(context.Background(), testPlanInput())
	if err == nil || !strings.Contains(err.Error(), "high-confidence secret value") {
		t.Fatalf("Plan() error = %v, want secret detection error", err)
	}
	if strings.Contains(err.Error(), secret) {
		t.Fatal("secret value appeared in error")
	}
}

func TestSecretPathCannotBeOverriddenOrRead(t *testing.T) {
	policy := testSourcePolicy()
	policy.RoleOverrides = []documentationmodel.RoleOverride{{Pattern: ".env", Role: sharedmodel.RoleProductionSource}}
	worktree := &fakeWorktree{}
	application := New(&fakeGitSource{root: "/repository", entries: []sharedmodel.TrackedEntry{{Path: ".env", Mode: "100644"}}}, worktree, &fakeState{result: sharedmodel.StateLoadResult{Missing: true}}, nil, nil)

	input := testPlanInput()
	input.SourcePolicy = policy
	result, err := application.Plan(context.Background(), input)
	if err != nil {
		t.Fatalf("Plan() error = %v", err)
	}
	if len(worktree.reads) != 0 {
		t.Fatalf("read paths = %v, secret path must not be read", worktree.reads)
	}
	decision := decisionByPath(t, result.Files, ".env")
	if decision.Role != sharedmodel.RoleSecret || decision.IncludedAsContext {
		t.Fatalf("decision = %+v, want denied secret", decision)
	}
}

