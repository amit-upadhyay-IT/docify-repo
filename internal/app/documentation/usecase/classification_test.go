type fakeWorktree struct {
	contents map[string]sharedmodel.FileContent
	reads    []string
}

type fakeState struct {
	result sharedmodel.StateLoadResult
	err    error
}

func (f *fakeState) Load(context.Context, string, string) (sharedmodel.StateLoadResult, error) {
	return f.result, f.err
}

func (f *fakeState) Decode(context.Context, []byte) (sharedmodel.StateLoadResult, error) {
	return f.result, f.err
}

func (f *fakeWorktree) ReadTracked(_ context.Context, _, repositoryPath string, _ int64) (sharedmodel.FileContent, error) {
	f.reads = append(f.reads, repositoryPath)
	content, exists := f.contents[repositoryPath]
	if !exists {
		return sharedmodel.FileContent{}, errors.New("unexpected read")
	}
	return content, nil
}

func testSourcePolicy() documentationmodel.SourcePolicy {
	return documentationmodel.SourcePolicy{
		DocsDir:      "docs/generated",
		StatePath:    ".docify/state.json",
		Include:      []string{"**/*"},
		Exclude:      []string{"vendor/**"},
		MaxFileBytes: 100,
		Tests:        documentationmodel.SourceBehavior{IncludeAsContext: true},
	}
}

func testPlanInput() documentationmodel.PlanInput {
	return documentationmodel.PlanInput{
		SourcePolicy: testSourcePolicy(),
		ComponentPolicy: documentationmodel.ComponentPolicy{
			Strategy: "inferred", MaxContextBytes: 1000, MaxBatchBytes: 500,
			MaxSupportingBytes: 200, MaxManifestBytes: 200, MaxDiffBytes: 200, MaxRequestBytes: 200_000,
		},
		GenerationPolicy: documentationmodel.GenerationPolicy{
			Profile: "codebase-summary", Audience: "mixed", Mermaid: true, Provider: "openai-compatible",
			APIMode: "chat_completions", MaxOutputTokens: 1024, StructuredOutputMode: "auto",
		},
	}
}

func textContent(repositoryPath, content string) sharedmodel.FileContent {
	return sharedmodel.FileContent{Path: repositoryPath, Data: []byte(content), Size: int64(len(content))}
}

func decisionByPath(t *testing.T, decisions []sharedmodel.SourceDecision, repositoryPath string) sharedmodel.SourceDecision {
	t.Helper()
	for _, decision := range decisions {
		if decision.Path == repositoryPath {
			return decision
		}
	}
	t.Fatalf("decision for %q not found", repositoryPath)
	return sharedmodel.SourceDecision{}
}

func sortDecisions(decisions []sharedmodel.SourceDecision) bool {
	for index := 1; index < len(decisions); index++ {
		if decisions[index-1].Path > decisions[index].Path {
			return false
		}
	}
	return true
}
